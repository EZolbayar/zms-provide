INSERT INTO dbo.TBCUSTOMERS (
    CUSTOMERID, BRANCHID, CLIENTTYPE, CLIENTNAME, DIRECTORNAME, FAMILYNAME, FIRSTNAME, PINID, NATIONALID, ORGPINID,
